"use strict";
const fs = require("fs"), assert = require("assert");
require("../js/belge.js");
const B = globalThis.PPBelge;
(async () => {
  const k = await B.kod("Ayşe  Yılmaz", "Siber Güvenlik", "2026-10-26");
  assert(/^[0-9A-F]{12}$/.test(k), "12 hane büyük hex");
  assert.strictEqual(k, await B.kod(" Ayşe Yılmaz ", "Siber Güvenlik", "2026-10-26"), "boşluklar normalleşir");
  assert.notStrictEqual(k, await B.kod("Ayşe Yılmaz", "Siber Güvenlik", "2026-10-27"), "tarih değişince kod değişir");
  assert.notStrictEqual(k, await B.kod("Ali Yılmaz", "Siber Güvenlik", "2026-10-26"), "ad değişince kod değişir");
  assert(await B.dogrula("Ayşe Yılmaz", "Siber Güvenlik", "2026-10-26", k.slice(0, 6) + "-" + k.slice(6).toLowerCase()), "tireli/küçük harf kabul");
  assert(!(await B.dogrula("Ayşe Yılmaz", "Siber Güvenlik", "2026-10-26", "000000000000")), "yanlış kod reddedilir");
  assert(B.tarihGecerli("2026-10-26") && !B.tarihGecerli("2026-13-45") && !B.tarihGecerli("<script>"), "tarih denetimi");
  const ui = fs.readFileSync(__dirname + "/../js/belge-ui.js", "utf8"), html = fs.readFileSync(__dirname + "/../belge.html", "utf8");
  assert(!/innerHTML/.test(ui), "ad/yol/kod innerHTML ile yazılmaz (XSS)");
  assert(/resmî sertifika(sı)? ya da sınav sonucu DEĞİLDİR/.test(html) && /bağımsız eğitim belgesi/.test(html), "sahte resmî iddia yok, etiket var");
  // Faz 34: tarayıcı senaryoları (taşma, kırpma, yazdırma, geçersiz tarih, marka)
  const { chromium } = require("playwright"), U = require("url").pathToFileURL(require("path").join(__dirname, "..", "belge.html")).href;
  const br = await chromium.launch(), ctx = await br.newContext({ viewport: { width: 375, height: 700 } }), p = await ctx.newPage();
  const uzun = "A".repeat(200);
  await p.goto(U + "?ad=" + uzun + "&hat=" + uzun + "&t=2026-10-26"); await p.waitForTimeout(300);
  assert.strictEqual(await p.evaluate(() => [document.getElementById("ad").value.length, document.getElementById("hat").value.length]).then(String), "80,80", "?ad/?hat 80 karaktere kırpılır");
  await p.click("#b"); await p.waitForTimeout(500);
  assert(await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), "uzun sonuç URL satırı 375 px'te yatay taşma yapmaz");
  const pr = await p.evaluate(() => { document.documentElement.setAttribute("data-t", "1"); return null; });
  await p.emulateMedia({ media: "print", colorScheme: "dark" });
  const yaz = await p.evaluate(() => ({ bg: getComputedStyle(document.body).backgroundColor, renk: getComputedStyle(document.body).color, sonuc: getComputedStyle(document.getElementById("sonuc")).display }));
  assert(yaz.bg === "rgb(255, 255, 255)" && yaz.sonuc === "none" && yaz.renk !== "rgb(255, 255, 255)", "yazdırmada açık zemin/koyu metin, durum satırı gizli: " + JSON.stringify(yaz));
  await p.emulateMedia({ media: "screen" });
  await p.goto(U + "?kod=ABCDEF123456&ad=Ali&hat=Siber&t=bozuk"); await p.waitForTimeout(300);
  assert(/tarih/i.test(await p.textContent("#sonuc")) && (await p.inputValue("#t")) === "", "doğrulamada geçersiz ?t= hata gösterir, sessizce bugüne dönmez");
  await p.goto(U + "?kod=ABCDEF123456&ad=Ali&hat=Siber"); await p.waitForTimeout(300);
  assert((await p.inputValue("#t")) === "" && /tarih/i.test(await p.textContent("#sonuc")), "doğrulamada eksik ?t= bugüne dönmez");
  assert((await p.title()).endsWith("FORNEX") && (await p.textContent(".belge .not")).includes("FORNEX"), "belge başlığı ve etiketi marka.js'ten (FORNEX)");
  await br.close();
  console.log("OK faz27_belge: 14 kontrol");
})().catch(e => { console.error("HATA", e.message); process.exit(1); });
